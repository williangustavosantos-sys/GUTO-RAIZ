// Read / set language
function getLang() {
  return localStorage.getItem("guto-lang") || "pt";
}
function setLang(l) {
  localStorage.setItem("guto-lang", l);
  window.GUTO_LANG = l;
}

window.GUTO_LANG = getLang();

function t(key) {
  const lang = window.GUTO_LANG || "pt";
  return (I18N[lang] && I18N[lang][key]) || (I18N.pt && I18N.pt[key]) || key;
}

